class mathfunctions{
    public static void main(String[] args) {
        int a =10;
        int b=5;
        System.out.println(Math.max(a,b));//prints the maximum value to the console
        System.out.println(Math.min(a,b));//prints the minimum value to the console
        System.out.println((a-b)+" "+Math.abs(a-b)+" "+(b-a)+" "+Math.abs(b-a));// prints the absolute value which means the positive of the result 
    }
}
